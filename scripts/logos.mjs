// Builds what the About books draw for each logo in public/logos:
//   1. public/logos/bitmap/<name>.webp  a pre-rendered picture of the SVG (the browser redraws vector logos at every
//      step of a 3D page turn, which flickers; a bitmap scales smoothly),
//   2. lib/design-v3/data/logos.ts      which file each logo uses.
// Run it after adding or changing a logo:  node scripts/logos.mjs
import { promises as fs } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const dir = path.join(process.cwd(), 'public', 'logos');
const out = path.join(dir, 'bitmap');
await fs.mkdir(out, { recursive: true });

const files = (await fs.readdir(dir)).filter((f) => /\.(svg|webp)$/.test(f)).sort();
const groups = new Map();
for (const f of files) {
  const m = f.match(/^(.*?)(-light|-dark)?\.(svg|webp)$/);
  if (!m) continue;
  const [, name, variant = '', ext] = m;
  if (!groups.has(name)) groups.set(name, {});
  groups.get(name)[variant + '.' + ext] = f;
}

const entries = [];
for (const [name, g] of [...groups].sort((a, b) => a[0].localeCompare(b[0]))) {
  const light = g['-light.svg'] || g['.svg'] || g['.webp'];
  if (!light) continue;
  const dark = g['-dark.svg'];
  let bitmap;
  if (light.endsWith('.svg')) {
    // 3x the largest size a logo is drawn at (about 190 x 65 CSS px), kept sharp and transparent
    const target = path.join(out, name + '.webp');
    await sharp(path.join(dir, light), { density: 384 }).resize({ width: 640, height: 220, fit: 'inside', withoutEnlargement: false }).webp({ lossless: true }).toFile(target);
    bitmap = '/logos/bitmap/' + name + '.webp';
  }
  entries.push({ name, light: '/logos/' + light, dark: dark ? '/logos/' + dark : undefined, bitmap });
}

const lines = [
  '// Which file to show for each logo in public/logos, so the page never asks for a file that is not there.',
  '// Generated by scripts/logos.mjs (run it after adding or changing a logo); a test checks it against the folder.',
  '// `light` is for light backgrounds (the dark-ink file when there is one); `dark` is the white version, where one exists.',
  '// `bitmap` is a pre-rendered picture of the SVG. The books use it, because vector logos flicker during a page turn.',
  '',
  'export const LOGOS: Record<string, { light: string; dark?: string; bitmap?: string }> = {',
  ...entries.map((e) => `  '${e.name}': { light: '${e.light}'${e.dark ? `, dark: '${e.dark}'` : ''}${e.bitmap ? `, bitmap: '${e.bitmap}'` : ''} },`),
  '};',
  '',
  '// The picture to draw: the bitmap when there is one.',
  'export const logoUrl = (name: string, onDark = false): string => {',
  '  const l = LOGOS[name];',
  '  if (!l) return `/logos/${name}.svg`;',
  '  return onDark && l.dark ? l.dark : l.bitmap ?? l.light;',
  '};',
  '',
  '// Load the logos ahead of time and keep them, so a page turn shows them at once instead of drawing them in.',
  'const kept: HTMLImageElement[] = [];',
  'export function preloadLogos(names: string[]) {',
  "  if (typeof window === 'undefined') return;",
  '  const seen = new Set(kept.map((i) => i.dataset.url));',
  '  for (const n of names) {',
  '    const url = logoUrl(n);',
  '    if (!n || seen.has(url)) continue;',
  '    seen.add(url);',
  '    const img = new Image();',
  '    img.dataset.url = url;',
  '    img.src = url;',
  '    img.decode().catch(() => {});',
  '    kept.push(img);',
  '  }',
  '}',
  '',
];
await fs.writeFile(path.join(process.cwd(), 'lib', 'design-v3', 'data', 'logos.ts'), lines.join('\n'));
console.log(entries.length + ' logos, ' + entries.filter((e) => e.bitmap).length + ' bitmaps');
